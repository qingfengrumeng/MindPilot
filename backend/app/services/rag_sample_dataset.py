def sample_dataset():
    documents, questions = [], []
    for index, (topic, rules) in enumerate(TOPICS):
        doc_id=f'synthetic-policy-{index+1:02d}'
        pages=[]
        for number,(title,rule,query) in enumerate(rules,1):
            intro=f'# 星桥实验企业 · {topic}\n\n## {number}. {title}\n\n本文件为人工构造的RAG评测样例，星桥实验企业为虚构机构。下面的制度只在此测试语料内成立，不用于真实业务决策。\n\n'
            text=intro+rule+'\n\n'
            text+=f'### 执行与复核\n负责此流程的人员应先核对申请所属业务、资料版本及审批责任，按“{title}”的具体要求判断是否满足执行条件。执行过程要留下申请时间、处理时间、执行人和处理结果。遇到材料缺失时，应说明缺失项并要求补充，不得将尚未满足条件的事项记为已完成。引用本制度回答问题时，应保留原文中的时间单位、金额范围、例外条件及责任主体；不能将工作日换成自然日，也不能把建议改写为强制要求。\n\n'
            text+=f'### 核对案例\n场景：工作人员收到一项与“{title}”有关的请求，需要判断下一步操作。其判断依据是：{rule}\n正确做法是分别检查触发条件、审批环节、执行期限与留档要求；对规则中未给出的城市名单、联系人电话、系统账号或费用比例，回答“测试文档未提供”，不能从其他主题推断。若当事人希望跳过审批或改变期限，应记录为例外申请，不能当作本条规则已变更。\n\n'
            text+=f'### 检索提示与版本约束\n本页只定义{topic}中的{title}，相似词出现在其他文件不代表规则相同。例如“审批”“保留”“响应”“恢复”应结合所在业务解释。优先引用原文证据，必要时引用其他主题的独立规则，并明确两条规则各自适用的对象。该评测样例版本为1，开发集用于调整检索参数，测试集用于检验未参与调优的问题，所有同一证据的改写问题都属于同一个分组。\n'
            pages.append({'page':number,'text':text})
            start=len(intro)
            for variant in range(2):
                questions.append({'id':f'{doc_id}-q{number:02d}-{variant}',
                    'query':query if variant==0 else f'根据星桥实验企业制度，请详细说明“{topic}”中“{title}”的条件、责任人、期限及例外要求，未给出的内容不要补充。',
                    'answer':rule,'split':'test' if number in {3,6} else 'dev','complete':True,
                    'judgments':{f'synthetic-policy-{j+1:02d}':3 if j==index else 0 for j in range(len(TOPICS))},
                    'evidence':[{'documentId':doc_id,'page':number,'start':start,'end':start+len(rule)}]})
        documents.append({'id':doc_id,'name':f'{index+1:02d}-{topic}（合成评测样例）.md','pages':pages})
    return {'schemaVersion':1,'documents':documents,'questions':questions}


def write_sample_files(root:Path):
    root.mkdir(parents=True,exist_ok=True)
    dataset=sample_dataset()
    (root/'rag-golden-dataset.json').write_text(json.dumps(dataset,ensure_ascii=False,indent=2),encoding='utf-8')
    for document in dataset['documents']:
        (root/document['name']).write_text('\n\n'.join(p['text'] for p in document['pages']),encoding='utf-8')
    (root/'README.md').write_text('# RAG 合成评测样例\n\n12份黄金文档、72页制度、144条带参考答案、相关性及原文位置的问答。96条开发集、48条测试集；同一事实的改写保持在同一分组。数据描述虚构机构，不是现实政策。\n\n可在RAG评测页面导入 rag-golden-dataset.json；每份Markdown也可独立上传。\n',encoding='utf-8')
    return dataset
